#!/bin/bash
# deploy.sh - ОДНА КОМАНДА для всего!

set -e

# ============================================
# КОНФИГУРАЦИЯ (ПОМЕНЯЙТЕ НА СВОЙ РЕПОЗИТОРИЙ)
# ============================================
REPO_URL="https://github.com/yukutakanawa/hestia-deploy.git"
TEMP_DIR="/tmp/hestia-deploy-$$"

# ============================================
# ФУНКЦИИ
# ============================================
print_header() {
    echo -e "\033[0;34m"
    echo "╔══════════════════════════════════════════════════════════╗"
    echo "║                                                          ║"
    echo "║     🚀  ONE-CLICK HESTIACP DEPLOY                       ║"
    echo "║     Просто запусти — и всё само установится!            ║"
    echo "║                                                          ║"
    echo "╚══════════════════════════════════════════════════════════╝"
    echo -e "\033[0m"
}

print_step() {
    echo -e "\n\033[0;36m▶ $1\033[0m"
    echo -e "\033[0;36m━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\033[0m"
}

print_success() {
    echo -e "\033[0;32m✅ $1\033[0m"
}

print_error() {
    echo -e "\033[0;31m❌ $1\033[0m"
}

print_info() {
    echo -e "\033[0;34mℹ️ $1\033[0m"
}

# ============================================
# ПРОВЕРКА ROOT
# ============================================
clear
print_header

if [ "$EUID" -ne 0 ]; then
    echo -e "\033[0;31m❌ Запустите скрипт от root!\033[0m"
    echo -e "\033[0;33mВыполните: sudo -i\033[0m"
    exit 1
fi

print_success "Запуск от root"

# ============================================
# 1. КЛОНИРОВАНИЕ РЕПОЗИТОРИЯ
# ============================================
print_step "Клонирование репозитория"

print_info "Репозиторий: $REPO_URL"

# Удаляем старую папку, если есть
rm -rf "$TEMP_DIR"

# Клонируем
git clone "$REPO_URL" "$TEMP_DIR" 2>/dev/null

if [ $? -ne 0 ]; then
    print_error "Не удалось клонировать репозиторий!"
    print_info "Проверьте URL: $REPO_URL"
    exit 1
fi

cd "$TEMP_DIR"
print_success "Репозиторий склонирован"

# ============================================
# 2. ПРОВЕРКА ФАЙЛОВ
# ============================================
print_step "Проверка файлов"

if [ ! -f "setup.sh" ]; then
    print_error "Файл setup.sh не найден в репозитории!"
    exit 1
fi

print_success "setup.sh найден"

# Показываем, какие файлы будут загружены
print_info "Файлы для загрузки:"
for file in *; do
    if [ "$file" != "setup.sh" ] && [ "$file" != "deploy.sh" ] && [ -f "$file" ]; then
        echo "  - $file"
    fi
done

# ============================================
# 3. ЗАПУСК УСТАНОВКИ
# ============================================
print_step "Запуск установки HestiaCP"

chmod +x setup.sh
./setup.sh

# ============================================
# 4. ОЧИСТКА
# ============================================
print_step "Очистка временных файлов"

cd /
rm -rf "$TEMP_DIR"
print_success "Временные файлы удалены"

# ============================================
# 5. ФИНИШ
# ============================================
echo ""
print_success "🎉 ВСЁ ГОТОВО!"
echo ""
echo -e "\033[0;32mПроверьте панель: https://ваш_хост:8083\033[0m"