#!/bin/bash
# deploy.sh - Одна команда для всего!

set -e

REPO_URL="https://github.com/yukutakanawa/hestia-deploy.git"
TEMP_DIR="/tmp/hestia-deploy-$$"

# ============================================
# ПРОВЕРКА ROOT
# ============================================
if [ "$EUID" -ne 0 ]; then
    echo "❌ Запустите от root: sudo -i"
    exit 1
fi

# ============================================
# ЗАГРУЗКА
# ============================================
echo "🚀 Загрузка репозитория..."
echo ""

# Удаляем старую папку, если есть
rm -rf "$TEMP_DIR"

# Клонируем
git clone "$REPO_URL" "$TEMP_DIR" 2>/dev/null

if [ $? -ne 0 ]; then
    echo "❌ Не удалось клонировать репозиторий!"
    echo "💡 Проверьте URL: $REPO_URL"
    exit 1
fi

cd "$TEMP_DIR"
echo "✅ Репозиторий склонирован"
echo ""

# ============================================
# ЗАПУСК
# ============================================
echo "🚀 Запуск setup.sh..."
echo ""

chmod +x setup.sh
./setup.sh

# ============================================
# ОЧИСТКА
# ============================================
cd /
rm -rf "$TEMP_DIR"
echo "✅ Временные файлы удалены"